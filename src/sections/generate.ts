/**
 * Turns index fixtures into the committed `sectionMap.generated.ts`.
 *
 * Pure functions only (no filesystem access); `scripts/build-section-map.mts`
 * and the tests both read the fixture files and call `buildEntries` +
 * `renderSectionMap`, so they always agree.
 */
import { normalize } from '../parser/normalize';
import { extractIndexEntries, mergeEntries } from './extract';
import type { PageEntry, PageRef } from './types';

/**
 * The index pages whose rows contribute page → title pairs. `199` (the
 * Päähakemisto) is first: it carries the canonical section names, and the
 * extractor keeps the first title it sees for a page.
 */
export const INDEX_PAGES: readonly number[] = [
  199, 160, 175, 200, 300, 330, 400, 410, 460, 470, 500, 575, 700, 799, 890,
];

/**
 * Page ranges that hold today's article pages. Index pages list their
 * headlines (e.g. 102 "Kotimaa" rows 103–107), and those change within hours,
 * so they must never be frozen into the map. Ranges follow the main index
 * (199): 103–159 news (101–102 and 130 are the index/section pages; 112 is
 * the only fixed page in there and is not worth a suggestion), 161–171
 * business news, 203–219 sports news, 221–222 the headline rows on 220/200.
 * Anything outside these ranges (e.g. 172 "Prime-korot", 223 "JÄÄKIEKKOLIIGA")
 * is a stable page name.
 */
export const HEADLINE_RANGES: readonly { readonly from: number; readonly to: number }[] = [
  { from: 103, to: 129 },
  { from: 131, to: 159 },
  { from: 161, to: 171 },
  { from: 203, to: 219 },
  { from: 221, to: 222 },
];

function isHeadlineEntry(entry: PageEntry): boolean {
  const from = typeof entry.page === 'number' ? entry.page : entry.page.from;
  const to = typeof entry.page === 'number' ? entry.page : entry.page.to;
  return HEADLINE_RANGES.some((range) => from >= range.from && to <= range.to);
}

/** Normalise raw API JSON, extract and merge entries, sorted and deduplicated. */
export function buildEntries(rawPages: unknown[]): PageEntry[] {
  const pages = rawPages
    .map((raw) => normalize(raw))
    .filter((result): result is Extract<typeof result, { ok: true }> => result.ok)
    .map((result) => result.page);
  return mergeEntries(
    pages.flatMap(extractIndexEntries).filter((entry) => !isHeadlineEntry(entry)),
  );
}

function renderPage(page: PageRef): string {
  if (typeof page === 'number') return String(page);
  return `{ from: ${page.from}, to: ${page.to} }`;
}

/**
 * Render a string as a single-quoted TS literal (Prettier's style here).
 * `JSON.stringify` does the escaping, so backslashes, quotes, newlines and
 * `*\/` in a Yle title can never end the literal early. The only changes are
 * the outer quotes: JSON's `\"` becomes `"` and raw `'` gets escaped.
 */
export function renderStringLiteral(value: string): string {
  const inner = JSON.stringify(value).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, "\\'");
  return `'${inner}'`;
}

/** Render the generated module source. */
export function renderSectionMap(entries: readonly PageEntry[]): string {
  const lines = entries.map((entry) => {
    const title = renderStringLiteral(entry.title);
    return `  { page: ${renderPage(entry.page)}, title: ${title} },`;
  });
  return [
    '// @generated by scripts/build-section-map.mts — do not edit.',
    '// Source: Yle teletext index pages listed in INDEX_PAGES (generate.ts)',
    '',
    "import type { PageEntry } from './types';",
    '',
    'export const SECTION_MAP: readonly PageEntry[] = [',
    ...lines,
    '];',
    '',
  ].join('\n');
}
